def translate_text(value: Any) -> Any:
    if not isinstance(value, str):
        return value
    match = re.fullmatch(r"Workbook generated with (\d+) warning\(s\)\.", value)
    if match:
        return f"工作簿已生成，有 {match.group(1)} 个项目需要复核。"
    text = value
    for old, new in MESSAGE_REPLACEMENTS:
        text = text.replace(old, new)
    return text


def translate_payload(value: Any, key: str | None = None) -> Any:
    if key in PASSTHROUGH_KEYS:
        return value
    if isinstance(value, dict):
        translated = {item_key: translate_payload(item, item_key) for item_key, item in value.items()}
        if "message" in translated:
            translated["message"] = translate_text(translated["message"])
        return translated
    if isinstance(value, list):
        return [translate_payload(item, key) for item in value]
    return translate_text(value)


def translated_response(response: JSONResponse) -> JSONResponse:
    data = json.loads(response.body.decode("utf-8"))
    return JSONResponse(translate_payload(data), status_code=response.status_code)


